import assert from 'node:assert/strict';
import {applyFallScheduleOverrides} from './fall-schedule-overrides.mjs';
const sheet=(title,values)=>({title,rows:[{cells:values.map(value=>({value}))}]});
const value=day=>`${day}\nLimited availability\n15:30–17:30 · Class booked · 华漕\n18:15–20:15 · Class booked · 龙柏`;
const input=[sheet('October 2026',[value(8),value(15),value(16),value(22)]),sheet('November 2026',[value(5)]),sheet('December 2026',[value(31)]),sheet('January 2027',[value(7)])];
const original=JSON.stringify(input),output=applyFallScheduleOverrides(input);
assert.equal(JSON.stringify(input),original);
for(const [s,c] of [[0,1],[0,3],[1,0],[2,0]]){assert.ok(!output[s].rows[0].cells[c].value.includes('18:15'));assert.ok(output[s].rows[0].cells[c].value.includes('15:30'));}
for(const [s,c] of [[0,0],[0,2],[3,0]])assert.equal(output[s].rows[0].cells[c].value,input[s].rows[0].cells[c].value);
assert.deepEqual(applyFallScheduleOverrides(output),output);
console.log('Fall cancellation boundaries, history, other classes and idempotence passed.');

const raw=applyFallScheduleOverrides([sheet('October 2026',['15\nLimited availability\n15:30–17:30 · SAS - 三年级\n18:15–20:15 · 井亭大厦 - 一年级'])]);
assert.equal(raw[0].rows[0].cells[0].value,'15\nLimited availability\n15:30–17:30 · SAS - 三年级');
const saturday='17\nLimited availability\n13:00–15:00 · Class booked · 古北\n15:30–17:30 · Class booked · 古北\n17:30–19:30 · Class booked · 古北';
const corrected=applyFallScheduleOverrides([sheet('October 2026',[saturday])]);
assert.ok(corrected[0].rows[0].cells[0].value.includes('15:00–16:30'));
assert.ok(corrected[0].rows[0].cells[0].value.includes('16:30–18:30'));
assert.ok(corrected[0].rows[0].cells[0].value.includes('13:00–15:00'));
assert.deepEqual(applyFallScheduleOverrides(corrected),corrected);
assert.equal(applyFallScheduleOverrides([sheet('September 2026',[saturday.replace(/^17/,'12')])])[0].rows[0].cells[0].value,saturday.replace(/^17/,'12'));
const tonight='20\nLimited availability\n17:30–19:30 · SAS - 六年级\n20:00–21:00 · Yilan Online 1-1';
const nextTuesday=tonight.replace(/^20/,'27');
const november='14\nLimited availability\n13:00–15:00 · Class booked · 古北\n15:30–17:30 · Class booked · 古北\n17:30–19:30 · Class booked · 古北';
const oneOffs=applyFallScheduleOverrides([sheet('October 2026',[tonight,nextTuesday]),sheet('November 2026',[november])]);
assert.ok(!oneOffs[0].rows[0].cells[0].value.includes('Yilan'));
assert.ok(oneOffs[0].rows[0].cells[0].value.includes('20:30–21:30 · Sharing at DPS'));
assert.equal(oneOffs[0].rows[0].cells[1].value,nextTuesday);
assert.ok(oneOffs[1].rows[0].cells[0].value.includes('10:00–12:00 · Sharing at Zhangjiang Toastmasters Club'));
assert.ok(oneOffs[1].rows[0].cells[0].value.includes('15:00–16:30'));
assert.deepEqual(applyFallScheduleOverrides(oneOffs),oneOffs);
