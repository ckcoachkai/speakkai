import assert from 'node:assert/strict';
import { itemDecision } from '../public/games/games/race3d-strategy.js';
import { rampAtDistance, planRampApproach, surfaceForWheel } from '../public/games/games/race3d-vehicle.js';
import { sampleRampSurface } from '../public/games/games/race3d-ramps.js';
import { auditStraightCorridor, safeRampSites } from '../public/games/games/race3d-course-safety.js';

const sampleTrack = d => ({ position: { x: 0, y: 0, z: d }, tangent: { x: 0, y: 0, z: 1 }, right: { x: 1, y: 0, z: 0 }, width: 18, bank: 0 });
const open = { totalLength: 1000, closed: false, sampleTrack }, closed = { totalLength: 1000, sampleTrack };
const ramp = { id: 'r1', distance: 100, lateral: 0, length: 22, width: 5.8, height: 2.6 };
assert.equal(sampleRampSurface(open, [ramp], 105).rampId, 'r1');
assert.equal(sampleRampSurface(open, [ramp], 1105).rampId, null);
assert.equal(sampleRampSurface(closed, [ramp], 1105).rampId, 'r1');
assert.deepEqual(rampAtDistance(ramp, 1105, 1000, { closed: false }), { start: 100, lap: 0 });
assert.deepEqual(rampAtDistance(ramp, 1105, 1000), { start: 1100, lap: 1 });
const racer = { id: 'a', distance: 1060, lateral: 0, speed: 20, heading: 0, rampId: 'r1', rampState: 'approach' };
assert.equal(planRampApproach(racer, [ramp], 1000, [], () => 0, { closed: false }), null);
assert.equal(planRampApproach(racer, [ramp], 1000).start, 1100);
const wheel = { x: 0, z: 0 };
const stale = { ...racer, distance: 1105 };
assert.equal(surfaceForWheel({ ...open, ramps: [ramp] }, stale, wheel, { extendLip: true }).lift, 0);
assert.ok(surfaceForWheel({ ...closed, ramps: [ramp] }, stale, wheel).lift > 0);
const nearLip = { ...racer, distance: 122.3 };
assert.ok(surfaceForWheel({ ...open, ramps: [ramp] }, nearLip, wheel, { extendLip: true }).lift > ramp.height);
const attacker = { id: 'a', distance: 980, lateral: 0, speed: 35, flightRemaining: 0, inventoryItem: 'missile', inventoryPhase: 'ready' };
const target = { id: 'b', distance: 10, lateral: 0, lateralVelocity: 0, speed: 30, flightRemaining: 0 };
assert.equal(itemDecision(attacker, [attacker, target], { trackLength: 1000, closed: false }).use, false);
assert.equal(itemDecision(attacker, [attacker, target], { trackLength: 1000 }).targetId, 'b');
const longTrack = { totalLength: 2000, closed: false, sampleTrack };
assert.equal(auditStraightCorridor(longTrack, 1600).reason, 'course-end');
assert.equal(auditStraightCorridor(longTrack, 300).safe, true);
const foldedSample = d => ({ ...sampleTrack(d), position: { x: 0, y: 0, z: d > 1800 ? d - 1900 : d } });
assert.equal(auditStraightCorridor({ totalLength: 2000, closed: false, sampleTrack: foldedSample }, 160).reason, 'near-intersection');
assert.equal(auditStraightCorridor({ totalLength: 2000, sampleTrack: foldedSample }, 160).safe, true);
const sites = safeRampSites({ totalLength: 4000, closed: false, sampleTrack });
assert.ok(sites.every(site => site.distance >= 100 && site.distance + site.length + 400 <= 4000));
console.log(JSON.stringify({ passed: true, tests: ['linear versus wrapped item targets', 'open and closed ramp surface', 'open and closed ramp approach', 'wheel support near and long after lip', 'open corridor bounds and endpoint intersection', 'safe ramp sites'] }, null, 2));
